#!/usr/bin/env python3
"""Builds Measured.lua: stat weights measured with the simulator, for classes that have a
simulator but no published weights yet.

Usage: python3 tools/measure_weights.py <path-to-wowsims-forever> <path-to-wowsimcli> [output-file]

For every reference character of such a class (builds/*.siml over the spec's defaults.siml)
the simulator runs once as it is and once per stat with a few points added. The damage gained
per point is that stat's weight, expressed in the class's power stat (ranged attack power,
attack power or spell damage, whichever is worth most), as in wowsims' own weights.

A class leaves this file by itself the day wowsims publishes weights for it: the addon then
uses those. The file is rewritten only when its content changes.
"""
import copy
import json
import subprocess
import sys
from pathlib import Path

from build_data import enum, lua_string, read_profiles
from calibrate import simulate

MEASURED_CLASSES = ["hunter"]
ITERATIONS = 5000
STEP, WEAPON_STEP = 50, 5  # points added of a stat, and of weapon damage per second
# Stats to measure, by their name in the simulator.
STATS = ["Strength", "Agility", "Intellect", "SpellDamage", "Spirit", "AttackPower", "RangedAttackPower",
         "HitRating", "CritRating", "HasteRating", "ArmorPenetration", "ExpertiseRating"]
# Capped stats: the reference character sits at its cap, where more is worth little. Their
# worth below the cap, which is what matters to anyone not capped, shows when points are taken away.
TAKEN_AWAY = {"HitRating", "ExpertiseRating"}
POWER_STATS = ["AttackPower", "RangedAttackPower", "SpellDamage"]
WEAPONS = {"mh": 0, "oh": 1, "rg": 2}  # addon key -> index of the simulator's weapon damage values
# Weights move a little with every simulator change. Steps of 0.05 keep those ripples from
# causing a release each day.
ROUND_TO = 0.05


def parse(cli, path):
    result = subprocess.run([str(cli), "siml", "parse", "-json", str(path)], capture_output=True, text=True, check=True)
    return json.loads(result.stdout)


def title(stem):
    """bm_weave -> "BM weave"."""
    return " ".join(word.upper() if len(word) <= 2 else word for word in stem.split("_"))


def measure(cli, stats, sizes, defaults, build_path):
    """Returns {"w": {stat index: weight}, "mh"/"oh"/"rg": weight}, or None if the build does no damage."""
    build = dict(defaults)
    player = {**defaults.get("player", {}), **parse(cli, build_path)["player"]}
    base = simulate(cli, build, player, ITERATIONS)
    if base <= 0:
        return None

    def gain(field, index, step):
        bumped = copy.deepcopy(player)
        values = bumped.setdefault("bonusStats", {}).setdefault(field, [])
        values.extend([0] * (sizes[field] - len(values)))  # the simulator wants the full list
        values[index] += step
        return (simulate(cli, build, bumped, ITERATIONS) - base) / step

    raw = {name: gain("stats", stats["Stat" + name], -STEP if name in TAKEN_AWAY else STEP) for name in STATS}
    unit = max(raw[name] for name in POWER_STATS)
    if unit <= 0:
        return None

    def rounded(value):
        return round(value / unit / ROUND_TO) * ROUND_TO

    profile = {"w": {}}
    for name in STATS:
        if rounded(raw[name]) > 0:
            profile["w"][stats["Stat" + name]] = rounded(raw[name])
    for key, index in WEAPONS.items():
        weight = rounded(gain("pseudoStats", index, WEAPON_STEP))
        if weight > 0:
            profile[key] = weight
    return profile


def main():
    sim, cli = Path(sys.argv[1]), Path(sys.argv[2]).resolve()
    target = Path(sys.argv[3]) if len(sys.argv) > 3 else Path(__file__).resolve().parent.parent / "Measured.lua"
    stats = enum((sim / "proto/common.proto").read_text(), "Stat")
    proto = (sim / "proto/common.proto").read_text()
    sizes = {"stats": max(stats.values()) + 1, "pseudoStats": max(enum(proto, "PseudoStat").values()) + 1}
    published = read_profiles(sim, stats)
    out = ["-- Generated by tools/measure_weights.py with the simulator of https://github.com/wowsims/forever. Do not edit.",
           "local _, ns = ...", "ns.Measured = {"]
    done = []
    for cls in MEASURED_CLASSES:
        if cls.upper() in published:
            done.append("%s: wowsims publishes weights now, nothing measured" % cls)
            continue
        lines = []
        for spec_dir in sorted(p for p in (sim / "ui/specs" / cls).iterdir() if (p / "defaults.siml").exists()):
            defaults = parse(cli, spec_dir / "defaults.siml")
            for build_path in sorted(spec_dir.glob("builds/*.siml")):
                profile = measure(cli, stats, sizes, defaults, build_path)
                if profile:
                    weights = ", ".join("[%d] = %g" % kv for kv in sorted(profile["w"].items()))
                    extra = "".join(", %s = %g" % (key, profile[key]) for key in WEAPONS if key in profile)
                    lines.append("\t\t{ name = %s, measured = true, w = { %s }%s }," % (lua_string(title(build_path.stem)), weights, extra))
        assert lines, "no reference character of %s could be measured" % cls
        out += ["\t%s = {" % cls.upper()] + lines + ["\t},"]
        done.append("%s: %d profiles" % (cls, len(lines)))
    out.append("}")
    body = "\n".join(out) + "\n"
    if target.exists() and target.read_text() == body:
        print("Measured.lua unchanged (%s)" % "; ".join(done))
        return
    target.write_text(body)
    print("Measured.lua written (%s)" % "; ".join(done))


if __name__ == "__main__":
    main()
